const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"playwright");
const fs=require("fs");
(async()=>{
 const b=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const p=await b.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];p.on("pageerror",e=>errors.push(String(e)));
 const shot=async(n)=>{await p.screenshot({path:"docs/images/desktop/"+n+".png",fullPage:true});};
 await p.goto(process.env.DOCS_DESKTOP_URL||"http://127.0.0.1:14210/?qa=device#/",{waitUntil:"networkidle"});
 await shot("device-disconnected");
 await p.getByRole("button",{name:"通过 USB 连接",exact:true}).click();
 await p.getByText("73%",{exact:false}).first().waitFor();
 await shot("device-connected");
 await p.getByRole("link",{name:"按键与层",exact:true}).click();
 await p.getByRole("button",{name:"command 5",exact:true}).click();
 await shot("layer1-mic");
 await p.getByRole("button",{name:"Typeless 按住说话",exact:false}).click();
 await p.getByRole("button",{name:"写入设备",exact:true}).click();
 await shot("mic-typeless");
 await p.getByRole("button",{name:/L2/}).click();
 await p.getByRole("button",{name:"command 1",exact:true}).click();
 await p.getByRole("button",{name:"复制",exact:false}).click();
 await shot("layer2-copy");
 await p.getByPlaceholder("例如 Control + Shift + P").fill("Control + Shift + P");
 await p.getByRole("button",{name:"应用点按映射",exact:true}).click();
 await shot("custom-shortcut");
 await p.getByRole("link",{name:"设置",exact:true}).click();
 await shot("settings-full");
 await p.getByRole("link",{name:"更新",exact:true}).click();
 await shot("updates-idle");
 await p.getByRole("button",{name:"认证并更新",exact:true}).click();
 await p.getByRole("button",{name:"确认应用",exact:true}).waitFor();
 await shot("update-confirm");
 console.log(JSON.stringify({screenshots:9,pageErrors:errors},null,2));
 await b.close();if(errors.length)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});